export const FONT_NAME = 'NotoSansSC';

type TextOptions = {
  name: string;
  content: string;
  x: number;
  y: number;
  width: number;
  height?: number;
  size?: number;
  color?: string;
  readOnly?: boolean;
  align?: 'left' | 'center' | 'right';
  weight?: 'normal' | 'bold';
};

const textField = ({
  name,
  content,
  x,
  y,
  width,
  height = 10,
  size = 12,
  color = '#171914',
  readOnly = false,
  align = 'left',
  weight = 'normal',
}: TextOptions) => ({
  name,
  type: 'text',
  position: { x, y },
  width,
  height,
  content,
  rotate: 0,
  opacity: 1,
  readOnly,
  required: !readOnly,
  fontName: FONT_NAME,
  fontSize: size,
  fontColor: color,
  backgroundColor: '',
  alignment: align,
  verticalAlignment: 'middle',
  lineHeight: 1.25,
  characterSpacing: weight === 'bold' ? 0.25 : 0,
});

const rect = (
  name: string,
  x: number,
  y: number,
  width: number,
  height: number,
  color: string,
  radius = 0,
) => ({
  name,
  type: 'rectangle',
  position: { x, y },
  width,
  height,
  content: '',
  rotate: 0,
  opacity: 1,
  readOnly: true,
  borderWidth: 0,
  borderColor: color,
  color,
  radius,
});

const line = (name: string, x: number, y: number, width: number, color = '#d8d5cc') => ({
  name,
  type: 'line',
  position: { x, y },
  width,
  height: 0.2,
  content: '',
  rotate: 0,
  opacity: 1,
  readOnly: true,
  color,
});

